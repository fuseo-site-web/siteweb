export type IconName = keyof typeof ICONS;

/** Icône Lucide décorative (aria-hidden) ; le sens est toujours porté par le texte voisin. */
export function Icon({
  name,
  size = 22,
  className,
  strokeWidth = 2,
}: {
  name: IconName;
  size?: number;
  className?: string;
  strokeWidth?: number;
}) {
  const Cmp = ICONS[name];
  return (
    <Cmp
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      aria-hidden="true"
      focusable="false"
    />
  );
}
